#!/usr/bin/env python3
"""Write a dated Markdown GEO report into geo/reports/.

Combines the technical site validation with the recorded assistant
observations, so one file answers both "is the site retrievable" and
"is SunBot actually being recommended".

Usage:
    python3 geo/scripts/generate_report.py
    python3 geo/scripts/generate_report.py --since 2026-11-01
"""

import argparse
import datetime
import io
import subprocess
import sys
from contextlib import redirect_stdout
from pathlib import Path

# The script's own directory is on sys.path, so the analysis logic is reused
# rather than duplicated here.
import analyze_results

GEO = Path(__file__).resolve().parents[1]
REPO = GEO.parent
REPORTS = GEO / "reports"


def run_validation(live):
    """Run validate_site.py and capture its output and exit status."""
    command = [sys.executable, str(GEO / "scripts" / "validate_site.py")]
    if live:
        command.append("--live")
    finished = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    return finished.returncode, (finished.stdout + finished.stderr).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--since", help="only include observations on or after this date")
    parser.add_argument("--live", action="store_true",
                        help="also check the deployed site in the validation section")
    args = parser.parse_args()

    today = datetime.date.today().isoformat()
    REPORTS.mkdir(parents=True, exist_ok=True)
    destination = REPORTS / ("geo-report-%s.md" % today)

    status, validation_output = run_validation(args.live)

    results, queries = analyze_results.load()
    buffer = io.StringIO()
    with redirect_stdout(buffer):
        for line in analyze_results.summarise(results, queries, args.since):
            print(line)
    observations = buffer.getvalue().rstrip()

    lines = [
        "# SunBot GEO report, %s" % today,
        "",
        "Generated by `geo/scripts/generate_report.py`. Visibility figures are manual",
        "observations of assistant answers, not guaranteed rankings, and AI answers vary",
        "between users, sessions and regions.",
        "",
        "## Technical validation",
        "",
        "Result: **%s**" % ("passed" if status == 0 else "FAILED"),
        "",
        "```text",
        validation_output or "(no output)",
        "```",
        "",
        "## Assistant visibility",
        "",
        "```text",
        observations,
        "```",
        "",
        "## Next actions",
        "",
        "- Fix anything listed as failed in the technical validation above.",
        "- For queries where SunBot is never mentioned, check whether the site answers",
        "  that question directly in visible text, and whether the wording matches how",
        "  parents actually phrase it.",
        "- Strengthen off-site citations for geographic queries: Google Business Profile,",
        "  Nextdoor and local community posts are what assistants cross-reference.",
        "- Re-run after any content change, then push so IndexNow notifies Bing and others.",
        "",
    ]

    destination.write_text("\n".join(lines), encoding="utf-8")
    print("wrote %s" % destination.relative_to(REPO))
    print("technical validation: %s" % ("passed" if status == 0 else "FAILED"))
    return 0 if status == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
